export function searchAyurvedaData(query, type) {
  if (!query) {
    if (type === 'medicine') {
      return defaultMedicines.map(m => ({
        title: m.allopathicName,
        snippet: `${m.purpose}. Natural substitutes: ${m.naturalAlternatives.map(a => a.name).join(', ')}.`,
        link: m.link,
        source: "AYUSH Natural Formulations",
        details: m
      }));
    }
    return defaultDiseases.map(d => ({
      title: d.title,
      snippet: `${d.snippet} Recommended herbs: ${d.keyHerbs.join(', ')}.`,
      link: d.link,
      source: `System: ${d.system}`,
      details: d
    }));
  }

  const q = query.toLowerCase().trim();

  if (type === 'medicine') {
    const matches = defaultMedicines.filter(m => 
      m.allopathicName.toLowerCase().includes(q) ||
      m.genericName.toLowerCase().includes(q) ||
      m.purpose.toLowerCase().includes(q) ||
      m.naturalAlternatives.some(a => 
        a.name.toLowerCase().includes(q) || 
        a.description.toLowerCase().includes(q)
      )
    );

    if (matches.length > 0) {
      return matches.map(m => ({
        title: m.allopathicName,
        snippet: `${m.purpose}. Natural alternatives include: ${m.naturalAlternatives.map(a => `${a.name} (${a.dosage})`).join('; ')}.`,
        link: m.link,
        source: "AYUSH Natural Formulations",
        details: m
      }));
    }

    // Fallback if not specifically found: return top alternatives with broad matching
    return defaultMedicines.slice(0, 3).map(m => ({
      title: m.allopathicName,
      snippet: `${m.purpose}. Natural alternatives include: ${m.naturalAlternatives.map(a => a.name).join(', ')}.`,
      link: m.link,
      source: "AYUSH Natural Formulations",
      details: m
    }));
  }

  // Type === 'disease'
  const matches = defaultDiseases.filter(d => 
    d.title.toLowerCase().includes(q) ||
    d.disease.toLowerCase().includes(q) ||
    d.category.toLowerCase().includes(q) ||
    d.keyHerbs.some(h => h.toLowerCase().includes(q)) ||
    d.snippet.toLowerCase().includes(q)
  );

  if (matches.length > 0) {
    return matches.map(d => ({
      title: d.title,
      snippet: `${d.snippet} Recommended herbs: ${d.keyHerbs.join(', ')}. Dosage: ${d.dosage}`,
      link: d.link,
      source: `System: ${d.system}`,
      details: d
    }));
  }

  // Fallback return top diseases
  return defaultDiseases.slice(0, 4).map(d => ({
    title: d.title,
    snippet: `${d.snippet} Recommended herbs: ${d.keyHerbs.join(', ')}. Dosage: ${d.dosage}`,
    link: d.link,
    source: `System: ${d.system}`,
    details: d
  }));
}
